type Raw = [q: string, options: [string, string, string, string], answer: number, explain: string]

function build(subject: string, topic: string, rows: Raw[], prefix: string): QuizQuestion[] {
  return rows.map(([q, options, answer, explain], i) => ({
    id: `${prefix}-${i + 1}`,
    q,
    options,
    answer,
    explain,
    subject,
    topic,
  }))
}

