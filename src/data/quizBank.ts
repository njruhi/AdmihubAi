export function filterBank(key: string): QuizQuestion[] {
  if (key === 'all') return QUIZ_BANK
  const [subject, topic] = key.split('|')
  return QUIZ_BANK.filter((q) => q.subject === subject && q.topic === topic)
}

export function shuffle<T>(arr: T[]): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

