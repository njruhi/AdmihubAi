export const KB_SUBJECTS = Array.from(new Set(KNOWLEDGE_BASE.map((k) => k.subject)))

export function searchKb(query: string): KbEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return KNOWLEDGE_BASE
  return KNOWLEDGE_BASE.filter((k) =>
    [k.title, k.topic, k.subject, k.body, ...(k.tags || [])].join(' ').toLowerCase().includes(q),
  )
}
